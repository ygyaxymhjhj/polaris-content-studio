import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const duplicateKeyErrors = [];
  page.on('console', message => { if (message.type() === 'error' && message.text().includes('same key')) duplicateKeyErrors.push(message.text()); });
  let article = { title: "Tin tức thị trường Forex ngày 07/09/2026", text: "Thị trường ngoại hối hôm nay. Độc giả cần đọc thông tin đầy đủ.", sourceUrl: "https://example.com/vi/newsdetail/a.html" };
  await page.route("**/api/fetch-article", route => route.fulfill({ json: article }));
  await page.route("**/api/analyze", route => route.fulfill({ json: { summaryShort: "Test", summaryLong: "Test summary", keyTerms: ['Forex', 'Forex'], riskFlags: ['high', 'high'], facts: [{ id: "F001", text: "Test fact", type: "claim", riskLevel: "low", sourceExcerpt: "Thị trường ngoại hối hôm nay.", sourceLocation: "p1", verified: false, usableOnSocial: true }] } }));
  await page.route('**/api/generate', route => route.fulfill({ json: { assets: [], usedFallback: false } }));
  await page.goto(process.env.TEST_BASE_URL || "http://localhost:3000");
  await page.locator('.locale-switcher select').selectOption("en");
  const field = name => page.getByLabel(name, { exact: true });
  const url = page.locator('.url-input-row input');
  await url.fill(article.sourceUrl);
  await page.getByRole('button', { name: 'Fetch article', exact: true }).click();
  await field('Project name').filter({ visible: true }).waitFor();
  await page.waitForFunction(title => document.querySelector('.input-grid input')?.value === title, article.title);
  assert.equal(await field('Project name').inputValue(), article.title);
  assert.equal(await field('Article title').inputValue(), article.title);
  assert.equal(await field('Category').inputValue(), 'Forex');
  assert.equal(await field('Language').inputValue(), 'vi');
  assert.equal(await field('Primary CTA').inputValue(), 'Đọc toàn bộ bài viết');
  await page.getByRole('button', { name: 'Generate social drafts', exact: true }).click();
  await page.getByRole('button', { name: 'Regenerate', exact: true }).waitFor();
  await page.locator('.nav-item').filter({ hasText: 'Source references' }).click();
  await page.getByRole('button', { name: 'Confirm displayed facts', exact: true }).waitFor();
  assert.equal(await page.locator('.risk-card li').count(), 1);
  assert.equal(await page.locator('.keyword-row > span').count(), 1);
  assert.deepEqual(duplicateKeyErrors, []);
  await page.getByRole('button', { name: 'Workspace', exact: true }).click();
  article = { title: '黄金市场观察', text: '黄金市场观察：请阅读原文并核实信息。', sourceUrl: 'https://example.com/zh/newsdetail/b.html' };
  await url.fill(article.sourceUrl);
  await page.getByRole('button', { name: 'Fetch article', exact: true }).click();
  await page.waitForFunction(title => document.querySelector('.input-grid input')?.value === title, article.title);
  assert.equal(await field('Language').inputValue(), 'zh');
  assert.equal(await field('Category').inputValue(), 'Gold');
  assert.equal(await page.locator('.input-grid input').last().inputValue(), article.sourceUrl);
  assert.equal(await page.locator('.existing-analysis').count(), 0);
  await field('Project name').fill('Custom campaign');
  await field('Language').selectOption('en');
  await field('Primary CTA').fill('Custom CTA');
  article = { title: 'A general update', text: 'A general update without any known category.', sourceUrl: 'https://example.com/article-c' };
  await url.fill(article.sourceUrl);
  await page.getByRole('button', { name: 'Fetch article', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.source-textarea')?.value.includes('without any known category'));
  assert.equal(await field('Project name').inputValue(), 'Custom campaign');
  assert.equal(await field('Primary CTA').inputValue(), 'Custom CTA');
  assert.equal(await field('Language').inputValue(), 'en');
  assert.equal(await field('Category').inputValue(), '');
  await page.locator('.source-textarea').fill('另一篇正文');
  assert.equal(await page.locator('.input-grid input').last().inputValue(), '');
  console.log('PASS: source alignment, Vietnamese/Chinese detection, category hints, updated links, stale analysis reset, preserved manual overrides and pasted source.');
} finally { await browser.close(); }
